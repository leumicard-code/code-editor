use fltk::enums::Color;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Rgb(pub u8, pub u8, pub u8);

impl Rgb {
    pub fn to_fltk(self) -> Color {
        Color::from_rgb(self.0, self.1, self.2)
    }
}

#[derive(Clone, Debug)]
pub struct EditorTheme {
    pub name: &'static str,
    pub syntect_theme: &'static str,
    pub bg: Rgb,
    pub gutter_bg: Rgb,
    pub gutter_fg: Rgb,
    pub gutter_active_fg: Rgb,
    pub text_fg: Rgb,
    pub cursor: Rgb,
    pub selection_bg: Rgb,
    pub active_line_bg: Rgb,
    pub indent_guide: Rgb,
    pub scrollbar_track: Rgb,
    pub scrollbar_thumb: Rgb,
    pub scrollbar_hover: Rgb,
    pub tab_bar_bg: Rgb,
    pub status_bg: Rgb,
    pub status_fg: Rgb,
    pub accent: Rgb,
    pub bracket_match_bg: Rgb,
    pub rainbow: [Rgb; 6],
}

impl EditorTheme {
    pub fn all() -> &'static [EditorTheme] {
        THEMES
    }

    pub fn by_index(idx: usize) -> &'static EditorTheme {
        &THEMES[idx % THEMES.len()]
    }
}

